                IF NEW.role IS DISTINCT FROM OLD.role THEN
                    RAISE EXCEPTION
                        'Role can only be changed by moderator';
                END IF;

                -- department ห้ามเปลี่ยนเอง
                IF NEW.department IS DISTINCT FROM OLD.department THEN
                    RAISE EXCEPTION
                        'Department can only be changed by moderator';
                END IF;

            END IF;

            RETURN NEW;

        END IF;

    END IF;

    RETURN NEW;

