create or replace function public.audit_users_write()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_action text;
    v_summary text;
    v_details jsonb;
    v_changes jsonb := '{}'::jsonb;
    v_previous_audit_flag text;
BEGIN

    -- service_role / internal writes ให้ trusted API เป็นคน audit
    IF auth.role() <> 'authenticated' THEN
        RETURN NEW;
    END IF;


    -- ========================================================
    -- INSERT
    -- ========================================================

    IF TG_OP = 'INSERT' THEN

        v_action := 'CREATE_USER';
        v_summary := 'สร้างผู้ใช้';

        v_details := jsonb_build_object(
            'id', NEW.id,
            'email', NEW.email,
            'name', NEW.name,
            'role', NEW.role,
            'employee_id', NEW.employee_id,
            'job_title', NEW.job_title,
            'department', NEW.department
        );


    -- ========================================================
    -- UPDATE
    -- ========================================================

    ELSE

        IF NEW.email IS DISTINCT FROM OLD.email THEN
            v_changes := v_changes || jsonb_build_object(
                'email',
                jsonb_build_object(
                    'old', OLD.email,
                    'new', NEW.email
                )
            );
        END IF;


        IF NEW.name IS DISTINCT FROM OLD.name THEN
            v_changes := v_changes || jsonb_build_object(
                'name',
                jsonb_build_object(
                    'old', OLD.name,
                    'new', NEW.name
                )
            );
        END IF;


        IF NEW.role IS DISTINCT FROM OLD.role THEN
            v_changes := v_changes || jsonb_build_object(
                'role',
                jsonb_build_object(
                    'old', OLD.role,
                    'new', NEW.role
                )
            );
        END IF;


        IF NEW.employee_id IS DISTINCT FROM OLD.employee_id THEN
            v_changes := v_changes || jsonb_build_object(
                'employee_id',
                jsonb_build_object(
                    'old', OLD.employee_id,
                    'new', NEW.employee_id
                )
            );
        END IF;


        IF NEW.job_title IS DISTINCT FROM OLD.job_title THEN
            v_changes := v_changes || jsonb_build_object(
                'job_title',
                jsonb_build_object(
                    'old', OLD.job_title,
                    'new', NEW.job_title
                )
            );
        END IF;


        IF NEW.department IS DISTINCT FROM OLD.department THEN
            v_changes := v_changes || jsonb_build_object(
                'department',
                jsonb_build_object(
                    'old', OLD.department,
                    'new', NEW.department
                )
            );
        END IF;


        IF NEW.signature_url IS DISTINCT FROM OLD.signature_url THEN
            v_changes := v_changes || jsonb_build_object(
                'signature_url',
                jsonb_build_object(
                    'old',
                    CASE
                        WHEN OLD.signature_url IS NULL
                        THEN NULL
                        ELSE '[signature]'
                    END,

                    'new',
                    CASE
                        WHEN NEW.signature_url IS NULL
                        THEN NULL
                        ELSE '[signature]'
                    END
                )
            );
        END IF;


        -- ไม่มี field สำคัญเปลี่ยนจริง
        IF v_changes = '{}'::jsonb THEN
            RETURN NEW;
        END IF;


        -- Self-profile update
        IF NEW.id = auth.uid()
           AND NEW.email IS NOT DISTINCT FROM OLD.email
           AND NEW.role IS NOT DISTINCT FROM OLD.role
           AND NEW.signature_url IS NOT DISTINCT FROM OLD.signature_url
        THEN
            v_action := 'UPDATE_PROFILE';
            v_summary := 'แก้ไขโปรไฟล์';

        ELSE
            v_action := 'UPDATE_USER';
            v_summary := 'แก้ไขข้อมูลผู้ใช้';
        END IF;


        v_details := jsonb_build_object(
            'id', NEW.id,
            'email', NEW.email,
            'name', NEW.name,
            'role', NEW.role
        );

    END IF;


    -- ========================================================
    -- TRUSTED AUDIT INSERT
    -- ========================================================

    v_previous_audit_flag :=
        current_setting(
            'app.audit_internal',
            true
        );


    PERFORM set_config(
        'app.audit_internal',
        'on',
        true
    );


    INSERT INTO public.audit_logs (
        action,
        summary,
        details,
        changes
    )
    VALUES (
        v_action,
        v_summary,
        v_details,
        CASE
            WHEN TG_OP = 'UPDATE'
            THEN v_changes
            ELSE NULL
        END
    );


    PERFORM set_config(
        'app.audit_internal',
        COALESCE(v_previous_audit_flag, ''),
        true
    );


    RETURN NEW;
END;
