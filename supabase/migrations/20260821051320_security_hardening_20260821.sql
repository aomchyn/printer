create or replace function public.audit_stability_feed_changes()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_action text;
    v_summary text;
    v_details jsonb;
    v_changes jsonb := '{}'::jsonb;
    v_previous_audit_flag text;
BEGIN

    -- ========================================================
    -- INSERT
    -- ========================================================

    IF TG_OP = 'INSERT' THEN

        v_action := 'CREATE_STABILITY_FEED';
        v_summary := 'สร้าง Stability Feed';

        v_details := jsonb_build_object(
            'id', NEW.id,
            'product_id', NEW.product_id,
            'product_name', NEW.product_name,
            'lot_number', NEW.lot_number
        );


    -- ========================================================
    -- UPDATE
    -- ========================================================

    ELSE

        -- เปลี่ยนแค่ updated_at ไม่ต้อง audit
        IF (
            to_jsonb(OLD)
            - ARRAY['updated_at']
        ) = (
            to_jsonb(NEW)
            - ARRAY['updated_at']
        ) THEN
            RETURN NEW;
        END IF;


        -- Soft delete
        IF COALESCE(OLD.is_deleted, false) = false
           AND COALESCE(NEW.is_deleted, false) = true
        THEN

            v_action := 'DELETE_STABILITY_FEED';
            v_summary := 'ลบ Stability Feed';

        ELSE

            v_action := 'UPDATE_STABILITY_FEED';
            v_summary := 'แก้ไข Stability Feed';

        END IF;


        -- ====================================================
        -- changes
        -- ====================================================

        IF NEW.lot_number IS DISTINCT FROM OLD.lot_number THEN
            v_changes := v_changes || jsonb_build_object(
                'lot_number',
                jsonb_build_object(
                    'old', OLD.lot_number,
                    'new', NEW.lot_number
                )
            );
        END IF;


        IF NEW.product_id IS DISTINCT FROM OLD.product_id THEN
            v_changes := v_changes || jsonb_build_object(
                'product_id',
                jsonb_build_object(
                    'old', OLD.product_id,
