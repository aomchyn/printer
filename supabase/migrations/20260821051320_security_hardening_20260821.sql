    v_name text;
    v_employee_id text;
    v_is_internal boolean;
BEGIN

    v_is_internal :=
        COALESCE(
            current_setting(
                'app.audit_internal',
                true
            ),
            'off'
        ) = 'on';


    IF auth.role() = 'authenticated' THEN

        IF NEW.action IN (

            -- orders
            'CREATE_ORDER',
            'UPDATE',
            'VERIFY',
            'UNVERIFY',
            'RECONCILE',
            'CANCEL_RECONCILE',
            'CANCEL',
            'DELETE_ORDER',
            'RESTORE_FROM_TRASH',
            'PERMANENT_DELETE_ORDER',

            -- products
            'CREATE_PRODUCT',
            'UPDATE_PRODUCT',
            'DELETE_PRODUCT',
            'DELETE_PRODUCTS',

            -- users
            'CREATE_USER',
            'UPDATE_USER',
            'UPDATE_PROFILE',
            'DELETE_USER',

            -- stability
            'CREATE_STABILITY_FEED',
            'UPDATE_STABILITY_FEED',
            'DELETE_STABILITY_FEED',

            -- stock
            'STOCK_IN',
            'STOCK_DELETE'

        )
        AND NOT v_is_internal THEN

            RAISE EXCEPTION
                'This audit action must be generated by the database or trusted server';

        END IF;


        SELECT
            u.name,
            u.employee_id
        INTO
            v_name,
            v_employee_id
        FROM public.users u
        WHERE u.id = auth.uid();


        IF NOT FOUND THEN
            RAISE EXCEPTION
                'User profile not found';
        END IF;


        NEW.user_id := auth.uid();

        NEW.user_name :=
            CASE
                WHEN NULLIF(
                    btrim(v_employee_id),
                    ''
                ) IS NOT NULL
                THEN
                    v_name
                    || ' ('
                    || v_employee_id
                    || ')'
                ELSE
                    v_name
            END;


        NEW.created_at := now();
        NEW.ip_address := NULL;

    END IF;


    RETURN NEW;
END;
