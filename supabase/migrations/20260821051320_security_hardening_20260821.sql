create or replace function public.audit_fgcode_delete()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_count integer;
    v_single_id text;
    v_ids jsonb;
    v_previous_audit_flag text;
BEGIN

    -- rename_fgcode() ลบ ID เก่า แต่ไม่ถือว่า DELETE_PRODUCT
    IF COALESCE(
        current_setting('app.fgcode_rename', true),
        'off'
    ) = 'on' THEN
        RETURN NULL;
    END IF;


    SELECT
        count(*),
        min(id),
        jsonb_agg(id ORDER BY id)
    INTO
        v_count,
        v_single_id,
        v_ids
    FROM deleted_rows;


    IF v_count = 0 THEN
        RETURN NULL;
    END IF;


    v_previous_audit_flag :=
        current_setting('app.audit_internal', true);

    PERFORM set_config(
        'app.audit_internal',
        'on',
        true
    );


    IF v_count = 1 THEN

        INSERT INTO public.audit_logs (
            action,
            details
        )
        VALUES (
            'DELETE_PRODUCT',
            jsonb_build_object(
                'id', v_single_id
            )
        );

    ELSE

        INSERT INTO public.audit_logs (
            action,
            details
        )
        VALUES (
            'DELETE_PRODUCTS',
            jsonb_build_object(
                'ids', v_ids,
                'count', v_count
            )
        );

    END IF;


    PERFORM set_config(
        'app.audit_internal',
        COALESCE(v_previous_audit_flag, ''),
        true
    );


    RETURN NULL;
END;
$function$;

create or replace function public.audit_fgcode_write()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_previous_audit_flag text;
    v_changes jsonb;
BEGIN

    -- rename_fgcode() จะสร้าง UPDATE_PRODUCT เอง 1 รายการ
    IF COALESCE(
        current_setting('app.fgcode_rename', true),
        'off'
    ) = 'on' THEN
        RETURN NEW;
    END IF;


    -- UPDATE ที่ไม่มีอะไรเปลี่ยนจริง ไม่ต้อง log
    IF TG_OP = 'UPDATE'
       AND NEW.name IS NOT DISTINCT FROM OLD.name
       AND NEW.exp IS NOT DISTINCT FROM OLD.exp
       AND NEW.default_paper_type IS NOT DISTINCT FROM OLD.default_paper_type
       AND NEW.qty_per_a3 IS NOT DISTINCT FROM OLD.qty_per_a3 THEN

        RETURN NEW;
    END IF;


    IF TG_OP = 'UPDATE' THEN

        v_changes := jsonb_strip_nulls(
            jsonb_build_object(

                'name',
                CASE
                    WHEN NEW.name IS DISTINCT FROM OLD.name
                    THEN jsonb_build_object(
                        'old', OLD.name,
                        'new', NEW.name
                    )
                END,

                'exp',
                CASE
                    WHEN NEW.exp IS DISTINCT FROM OLD.exp
                    THEN jsonb_build_object(
                        'old', OLD.exp,
                        'new', NEW.exp
                    )
                END,

                'default_paper_type',
                CASE
                    WHEN NEW.default_paper_type
                         IS DISTINCT FROM OLD.default_paper_type
                    THEN jsonb_build_object(
                        'old', OLD.default_paper_type,
                        'new', NEW.default_paper_type
                    )
                END,

                'qty_per_a3',
                CASE
                    WHEN NEW.qty_per_a3
                         IS DISTINCT FROM OLD.qty_per_a3
                    THEN jsonb_build_object(
                        'old', OLD.qty_per_a3,
                        'new', NEW.qty_per_a3
                    )
                END
            )
        );

    ELSE
        v_changes := NULL;
    END IF;


    v_previous_audit_flag :=
        current_setting('app.audit_internal', true);

    PERFORM set_config(
        'app.audit_internal',
        'on',
        true
    );


    INSERT INTO public.audit_logs (
        action,
        details,
        changes
    )
    VALUES (
        CASE
            WHEN TG_OP = 'INSERT'
                THEN 'CREATE_PRODUCT'
            ELSE 'UPDATE_PRODUCT'
        END,

        jsonb_build_object(
            'id', NEW.id,
            'name', NEW.name,
            'exp', NEW.exp,
            'default_paper_type', NEW.default_paper_type,
            'qty_per_a3', NEW.qty_per_a3
        ),

        v_changes
    );


    PERFORM set_config(
        'app.audit_internal',
        COALESCE(v_previous_audit_flag, ''),
        true
    );


    RETURN NEW;
END;
$function$;

create or replace function public.audit_orders_changes()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_action text;
    v_summary text;
    v_details jsonb;
    v_previous_audit_flag text;
BEGIN

    -- การ sync ภายในจาก fgcode ไม่สร้าง order audit ปลอม/ซ้ำ
    IF COALESCE(
        current_setting('app.order_internal_write', true),
        'off'
    ) = 'on' THEN

        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        END IF;

        RETURN NEW;
    END IF;


    -- ========================================================
    -- INSERT = CREATE_ORDER
    -- ========================================================
    IF TG_OP = 'INSERT' THEN

        v_action := 'CREATE_ORDER';
        v_summary := 'สร้างคำสั่งพิมพ์';

        v_details := jsonb_build_object(
            'order_id', NEW.id,
            'product_id', NEW.product_id,
            'product_name', NEW.product_name,
            'lot_number', NEW.lot_number,
            'quantity', NEW.quantity
        );


    -- ========================================================
    -- DELETE จริง = PERMANENT_DELETE_ORDER
    -- ========================================================
    ELSIF TG_OP = 'DELETE' THEN

        v_action := 'PERMANENT_DELETE_ORDER';
        v_summary := 'ลบคำสั่งพิมพ์ถาวร';

        v_details := jsonb_build_object(
            'order_id', OLD.id,
            'product_id', OLD.product_id,
            'product_name', OLD.product_name,
            'lot_number', OLD.lot_number,
            'quantity', OLD.quantity,
            'created_by', OLD.created_by,
            'deleted_by', OLD.deleted_by,
            'deleted_at', OLD.deleted_at
        );


    -- ========================================================
    -- UPDATE
    -- ========================================================
    ELSE

        -- Soft delete
        IF COALESCE(OLD.is_deleted, false) = false
           AND COALESCE(NEW.is_deleted, false) = true THEN

            v_action := 'DELETE_ORDER';
            v_summary := COALESCE(
                NULLIF(NEW.edit_summary, ''),
                'ย้ายคำสั่งพิมพ์ไปถังขยะ'
            );

            v_details := jsonb_build_object(
                'order_id', NEW.id,
                'product_id', NEW.product_id,
                'product_name', NEW.product_name,
                'lot_number', NEW.lot_number,
                'quantity', NEW.quantity,
                'created_by', NEW.created_by,
                'deleted_by', NEW.deleted_by,
                'deleted_at', NEW.deleted_at
            );


        -- Restore
        ELSIF COALESCE(OLD.is_deleted, false) = true
           AND COALESCE(NEW.is_deleted, false) = false THEN

            v_action := 'RESTORE_FROM_TRASH';
            v_summary := COALESCE(
                NULLIF(NEW.edit_summary, ''),
                'กู้คืนคำสั่งพิมพ์จากถังขยะ'
            );

            v_details := jsonb_build_object(
                'order_id', NEW.id,
                'product_id', NEW.product_id,
                'product_name', NEW.product_name,
                'lot_number', NEW.lot_number
            );


        -- Verify
        ELSIF COALESCE(OLD.is_verified, false) = false
           AND COALESCE(NEW.is_verified, false) = true THEN

            v_action := 'VERIFY';
            v_summary := 'ตรวจสอบและยืนยันคำสั่งพิมพ์';
            v_details := NULL;


        -- Unverify
        ELSIF COALESCE(OLD.is_verified, false) = true
           AND COALESCE(NEW.is_verified, false) = false THEN

            v_action := 'UNVERIFY';
            v_summary := 'ยกเลิกการยืนยันคำสั่งพิมพ์';
            v_details := NULL;


        -- Cancel
        ELSIF COALESCE(OLD.is_cancelled, false) = false
           AND COALESCE(NEW.is_cancelled, false) = true THEN

            v_action := 'CANCEL';
            v_summary := COALESCE(
                NULLIF(NEW.edit_summary, ''),
                'ยกเลิกคำสั่งพิมพ์'
            );
            v_details := NULL;


        -- Reconcile
        ELSIF OLD.reconciled_at IS NULL
           AND NEW.reconciled_at IS NOT NULL THEN

            v_action := 'RECONCILE';

            v_summary :=
                'บันทึกผลผลิต: กระดาษดี '
                || COALESCE(NEW.good_a3, 0)::text
                || ' ใบ, เสีย '
                || COALESCE(NEW.waste_a3, 0)::text
                || ' ใบ';

            v_details := NULL;


        -- Cancel reconcile
        ELSIF OLD.reconciled_at IS NOT NULL
           AND NEW.reconciled_at IS NULL THEN

            v_action := 'CANCEL_RECONCILE';
            v_summary := 'ยกเลิกการตัดสต็อคกระดาษ';
            v_details := NULL;


        -- UPDATE ปกติ
        ELSE

            -- ถ้าเปลี่ยนแค่ metadata ที่ระบบ stamp เอง
            -- ไม่ต้องสร้าง audit เพิ่ม
            IF (
                to_jsonb(OLD)
                - ARRAY[
                    'updated_at',
                    'updated_by',
                    'edit_summary'
                ]
            ) = (
                to_jsonb(NEW)
                - ARRAY[
                    'updated_at',
                    'updated_by',
                    'edit_summary'
                ]
            ) THEN
                RETURN NEW;
            END IF;

            v_action := 'UPDATE';

            v_summary := COALESCE(
                NULLIF(NEW.edit_summary, ''),
                'แก้ไขคำสั่งพิมพ์'
            );

            v_details := NULL;

        END IF;

    END IF;


    -- ========================================================
    -- เปิด trusted flag เฉพาะภายใน transaction นี้
    -- ========================================================

    v_previous_audit_flag :=
        current_setting('app.audit_internal', true);

    PERFORM set_config(
        'app.audit_internal',
        'on',
        true
    );


    INSERT INTO public.audit_logs (
        user_id,
        order_id,
        action,
        summary,
        details
    )
    VALUES (
        auth.uid(),
        CASE
            WHEN TG_OP = 'DELETE' THEN OLD.id
            ELSE NEW.id
        END,
        v_action,
        v_summary,
        v_details
    );


    PERFORM set_config(
        'app.audit_internal',
        COALESCE(v_previous_audit_flag, ''),
        true
    );


    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$function$;

create or replace function public.audit_paper_transaction_delete()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_total integer;
    v_row public.paper_transactions%ROWTYPE;
    v_previous_audit_flag text;
BEGIN

    IF auth.role() <> 'authenticated' THEN
        RETURN NULL;
    END IF;


    SELECT count(*)
    INTO v_total
    FROM deleted_rows;


    IF v_total <> 1 THEN
        RETURN NULL;
    END IF;


    SELECT *
    INTO v_row
    FROM deleted_rows
    LIMIT 1;


    -- transaction ที่ผูก source ต้องถูกจัดการจาก workflow ต้นทาง
    IF v_row.reference_id IS NOT NULL THEN
        RETURN NULL;
    END IF;


    v_previous_audit_flag :=
        current_setting(
            'app.audit_internal',
            true
        );


    PERFORM set_config(
        'app.audit_internal',
        'on',
        true
    );


    INSERT INTO public.audit_logs (
        action,
        summary,
        details
    )
    VALUES (
        'STOCK_DELETE',
        'ลบรายการ Stock',
        jsonb_build_object(
            'id', v_row.id,
            'paperType', v_row.paper_type,
            'qty', v_row.qty,
            'type', v_row.transaction_type
        )
    );


    PERFORM set_config(
        'app.audit_internal',
        COALESCE(v_previous_audit_flag, ''),
        true
