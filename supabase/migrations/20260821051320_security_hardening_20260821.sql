create or replace function public.rename_fgcode (
  p_old_id             text,
  p_new_id             text,
  p_name               text,
  p_exp                text,
  p_default_paper_type text    default null::text,
  p_qty_per_a3         integer default null::integer
)
  returns integer
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_old public.fgcode%ROWTYPE;
    v_affected integer := 0;
    v_editor text;

    v_previous_rename_flag text;
    v_previous_audit_flag text;
BEGIN

    IF auth.role() <> 'authenticated' THEN
        RAISE EXCEPTION 'Authentication required';
    END IF;


    IF NOT public.is_user_manager() THEN
        RAISE EXCEPTION
            'Only Moderator or Assistant Moderator can change Product ID';
    END IF;


    p_old_id := btrim(p_old_id);
    p_new_id := btrim(p_new_id);
    p_name := btrim(p_name);
    p_exp := btrim(p_exp);


    IF p_old_id = ''
       OR p_new_id = '' THEN
        RAISE EXCEPTION 'Product ID cannot be empty';
    END IF;


    IF p_old_id = p_new_id THEN
        RAISE EXCEPTION
            'New Product ID must be different';
    END IF;


    IF p_name = '' THEN
        RAISE EXCEPTION
            'Product name cannot be empty';
    END IF;


    IF p_exp = ''
       OR p_exp !~ '^[0-9]+$'
       OR p_exp::integer <= 0 THEN
        RAISE EXCEPTION
            'Invalid product expiry';
    END IF;


    IF p_qty_per_a3 IS NOT NULL
       AND p_qty_per_a3 <= 0 THEN
        RAISE EXCEPTION
            'qty_per_a3 must be greater than 0';
    END IF;


    SELECT *
    INTO v_old
    FROM public.fgcode
    WHERE id = p_old_id
    FOR UPDATE;


    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Product ID "%" not found',
            p_old_id;
    END IF;


    IF EXISTS (
        SELECT 1
        FROM public.fgcode
        WHERE id = p_new_id
    ) THEN
        RAISE EXCEPTION
            'Product ID "%" already exists',
            p_new_id;
    END IF;


    SELECT
        CASE
            WHEN u.employee_id IS NOT NULL
                 AND btrim(u.employee_id) <> ''
            THEN u.name || ' (' || u.employee_id || ')'
            ELSE u.name
        END
    INTO v_editor
    FROM public.users u
    WHERE u.id = auth.uid();


    v_editor := COALESCE(
        v_editor,
        'System'
    );


    -- ========================================================
    -- เปิด rename flag
    -- ป้องกัน trigger มอง INSERT+DELETE เป็น Create/Delete
    -- ========================================================

    v_previous_rename_flag :=
        current_setting(
            'app.fgcode_rename',
            true
        );


    PERFORM set_config(
        'app.fgcode_rename',
        'on',
        true
    );


    -- ========================================================
    -- สร้าง Product ID ใหม่
    -- ========================================================

    INSERT INTO public.fgcode (
        id,
        name,
        exp,
        created_at,
        default_paper_type,
        qty_per_a3
    )
    VALUES (
        p_new_id,
        p_name,
        p_exp,
        v_old.created_at,
        NULLIF(
            btrim(p_default_paper_type),
            ''
        ),
        p_qty_per_a3
    );


    -- ========================================================
    -- ย้าย Product ID ของ orders
    -- ========================================================

    WITH moved_orders AS (

        UPDATE public.orders o
        SET
            product_id = p_new_id,

            previous_product_name =
                CASE
                    WHEN o.is_verified = false
                         AND COALESCE(
                             o.is_cancelled,
                             false
                         ) = false
                         AND o.product_name
                             IS DISTINCT FROM p_name
                    THEN o.product_name
                    ELSE o.previous_product_name
                END,

            product_name =
                CASE
                    WHEN o.is_verified = false
                         AND COALESCE(
                             o.is_cancelled,
                             false
                         ) = false
                    THEN p_name
                    ELSE o.product_name
                END,

            product_exp =
                CASE
                    WHEN o.is_verified = false
                         AND COALESCE(
                             o.is_cancelled,
                             false
                         ) = false
                    THEN p_exp
                    ELSE o.product_exp
                END,

            expiry_date =
                CASE
                    WHEN o.is_verified = false
                         AND COALESCE(
                             o.is_cancelled,
                             false
                         ) = false
                    THEN (
                        o.production_date
                        + make_interval(
                            months => p_exp::integer
                        )
                    )::date
                    ELSE o.expiry_date
                END,

            updated_at =
                CASE
                    WHEN o.is_verified = false
                         AND COALESCE(
                             o.is_cancelled,
                             false
                         ) = false
                    THEN now()
                    ELSE o.updated_at
                END,

            updated_by =
                CASE
                    WHEN o.is_verified = false
                         AND COALESCE(
                             o.is_cancelled,
                             false
                         ) = false
                    THEN v_editor
                    ELSE o.updated_by
                END,

            edit_summary =
                CASE
                    WHEN o.is_verified = false
                         AND COALESCE(
                             o.is_cancelled,
                             false
                         ) = false
                    THEN format(
                        'รหัสสินค้าเปลี่ยน: %s ➡️ %s',
                        p_old_id,
                        p_new_id
                    )
                    ELSE o.edit_summary
                END

        WHERE o.product_id = p_old_id

        RETURNING o.id
    )

    SELECT count(*)
    INTO v_affected
    FROM moved_orders;


    -- ========================================================
    -- ลบ ID เดิม
    -- ========================================================

    DELETE FROM public.fgcode
    WHERE id = p_old_id;


    -- ========================================================
    -- Product-level trusted audit
    -- ========================================================

    v_previous_audit_flag :=
        current_setting(
            'app.audit_internal',
            true
        );


    PERFORM set_config(
        'app.audit_internal',
        'on',
        true
    );


    INSERT INTO public.audit_logs (
        action,
        details,
        changes
    )
    VALUES (
        'UPDATE_PRODUCT',

        jsonb_build_object(
            'old_id', p_old_id,
            'id', p_new_id,
            'name', p_name,
            'exp', p_exp,
            'default_paper_type',
                NULLIF(
                    btrim(p_default_paper_type),
                    ''
                ),
            'qty_per_a3', p_qty_per_a3,
            'affected_orders', v_affected
        ),

        jsonb_build_object(
            'id',
            jsonb_build_object(
                'old', p_old_id,
                'new', p_new_id
            )
        )
    );


    PERFORM set_config(
        'app.audit_internal',
        COALESCE(v_previous_audit_flag, ''),
        true
    );


    PERFORM set_config(
        'app.fgcode_rename',
        COALESCE(v_previous_rename_flag, ''),
        true
    );


    RETURN v_affected;
END;
$function$;

