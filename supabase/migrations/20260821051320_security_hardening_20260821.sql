  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_is_manager boolean := false;
BEGIN

    IF auth.role() = 'authenticated' THEN

        v_is_manager := public.is_user_manager();

        -- =========================================
        -- INSERT
        -- =========================================
        IF TG_OP = 'INSERT' THEN

            IF NOT v_is_manager THEN

