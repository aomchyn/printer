    RETURN NULL;
END;
$function$;

create or replace function public.audit_paper_transaction_insert()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_total integer;
    v_row public.paper_transactions%ROWTYPE;
    v_previous_audit_flag text;
BEGIN

    IF auth.role() <> 'authenticated' THEN
        RETURN NULL;
    END IF;


    SELECT count(*)
    INTO v_total
    FROM inserted_rows;


    -- STOCK page insert ทีละ 1 รายการ
    IF v_total <> 1 THEN
        RETURN NULL;
    END IF;


    SELECT *
    INTO v_row
    FROM inserted_rows
    LIMIT 1;


    -- STOCK_IN = manual IN ที่ไม่ได้ผูก Order/Report
    IF v_row.transaction_type <> 'IN'
       OR v_row.reference_id IS NOT NULL
       OR v_row.transaction_category IS NOT NULL THEN

        RETURN NULL;

    END IF;


    -- weekly reset carry-forward ไม่ถือเป็น manual STOCK_IN
    IF v_row.description =
       'ยกยอดสต็อคคงเหลือจากการรีเซ็ตประจำสัปดาห์'
    THEN
        RETURN NULL;
    END IF;


    v_previous_audit_flag :=
        current_setting(
            'app.audit_internal',
            true
        );


    PERFORM set_config(
        'app.audit_internal',
        'on',
        true
    );


    INSERT INTO public.audit_logs (
        action,
        summary,
        details
    )
    VALUES (
        'STOCK_IN',
        'รับกระดาษเข้าส stock',
        jsonb_build_object(
            'id', v_row.id,
            'paperType', v_row.paper_type,
            'qty', v_row.qty,
