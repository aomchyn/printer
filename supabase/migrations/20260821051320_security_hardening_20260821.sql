create or replace function public.sync_orders_from_fgcode()
  returns trigger
  language plpgsql
  security definer
  set search_path to ''
  AS $function$
DECLARE
    v_editor text;
    v_summary text;
    v_previous_internal_flag text;
BEGIN

    IF NEW.name IS NOT DISTINCT FROM OLD.name
       AND NEW.exp IS NOT DISTINCT FROM OLD.exp THEN
        RETURN NEW;
    END IF;


    SELECT
        CASE
            WHEN u.employee_id IS NOT NULL
                 AND btrim(u.employee_id) <> ''
            THEN u.name || ' (' || u.employee_id || ')'
            ELSE u.name
        END
    INTO v_editor
    FROM public.users u
    WHERE u.id = auth.uid();


    v_editor := COALESCE(v_editor, 'System');


    v_summary := concat_ws(
        ' | ',

        CASE
            WHEN NEW.name IS DISTINCT FROM OLD.name
            THEN format(
                'ชื่อสินค้าเปลี่ยน: %s ➡️ %s',
                OLD.name,
                NEW.name
            )
        END,

        CASE
            WHEN NEW.exp IS DISTINCT FROM OLD.exp
            THEN format(
                'อายุผลิตภัณฑ์เปลี่ยน: %s ➡️ %s เดือน',
                OLD.exp,
                NEW.exp
            )
        END
    );


    v_previous_internal_flag :=
        current_setting(
            'app.order_internal_write',
            true
        );


    -- bypass protection เฉพาะ DB sync นี้
    PERFORM set_config(
        'app.order_internal_write',
        'on',
        true
    );


    UPDATE public.orders o
    SET
        previous_product_name =
            CASE
                WHEN NEW.name IS DISTINCT FROM OLD.name
                THEN o.product_name
                ELSE o.previous_product_name
            END,

        product_name =
            CASE
                WHEN NEW.name IS DISTINCT FROM OLD.name
                THEN NEW.name
                ELSE o.product_name
            END,

        product_exp =
            CASE
                WHEN NEW.exp IS DISTINCT FROM OLD.exp
                THEN NEW.exp
                ELSE o.product_exp
            END,

        expiry_date =
            CASE
                WHEN NEW.exp IS DISTINCT FROM OLD.exp
                     AND btrim(NEW.exp) ~ '^[0-9]+$'
                THEN (
                    o.production_date
                    + make_interval(
                        months => btrim(NEW.exp)::integer
                    )
                )::date
                ELSE o.expiry_date
            END,

        updated_at = now(),
        updated_by = v_editor,
        edit_summary = v_summary

    WHERE o.product_id = NEW.id
      AND o.is_verified = false
      AND COALESCE(o.is_cancelled, false) = false;


    PERFORM set_config(
        'app.order_internal_write',
        COALESCE(v_previous_internal_flag, ''),
        true
    );


    RETURN NEW;
END;
$function$;

